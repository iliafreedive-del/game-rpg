export const NAMES = new Set(['bram', 'mira', 'hild', 'owen', 'tom', 'stillford', 'osric']);

export const ALL_WORD_IDS = Object.keys(WORDS);
export const FORM = {};   // surface form -> lemma id
for (const [id, w] of Object.entries(WORDS)) { FORM[id] = id; for (const f of w.forms) FORM[f] = id; w.id = id; }
for (const p of PAGES) for (const id of p.words) { if (!WORDS[id]) throw new Error('page word ' + id); WORDS[id].page = p.id; WORDS[id].ch = p.ch; }

const norm = s => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9 ]/g, '').replace(/\s+/g, ' ').trim();
export { norm };
// does a free-text Russian guess match this word?
export function guessMatches(id, guess) {
  const g = norm(guess || ''); if (!g) return false;
  const w = WORDS[id]; const acc = [w.ru, ...w.alt].map(norm);
  for (const a of acc) {
    if (g === a) return true;
    if (g.split(' ').includes(a) && a.length >= 2) return true;
    const L = Math.max(4, a.length - 2);
    if (a.length >= 4 && g.length >= 4 && g.slice(0, L) === a.slice(0, L)) return true;
  }
  return false;
}
// split English text into tokens: {t:'word', raw, id?, fn?, name?} | {t:'sep', raw}
export function tokenize(text) {
  const out = []; const re = /([A-Za-z]+)|([^A-Za-z]+)/g; let m;
  while ((m = re.exec(text))) {
    if (m[1]) { const low = m[1].toLowerCase(); const id = FORM[low]; out.push({ t: 'word', raw: m[1], id, fn: !id && FN[low] !== undefined ? low : null, name: !id && NAMES.has(low) }); }
    else out.push({ t: 'sep', raw: m[2] });
  }
  return out;
}
