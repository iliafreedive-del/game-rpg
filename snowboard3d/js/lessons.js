// Учебная программа: теория, мастер-класс, цель упражнения, проверка и «инструктор-автопилот».
import { wrapAngle } from './sim.js';

const D = Math.PI / 180;
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

// Удержать курс θd регулировкой веса (так работает «падающий лист»: нагруженный конец держит, разгруженный уходит вниз).
function weightForHeading(sim, thd, gain = 2.2, lim = 0.7) {
  const err = wrapAngle(sim.theta - thd);
  const sn = Math.sin(sim.theta);
  if (Math.abs(sn) < 0.2) return 0;
  return clamp(gain * err / (1.8 * sn), -lim, lim);
}

// Демонстрация соскальзывания: кант — регулятор скорости. Меньше канта — быстрее, больше — медленнее,
// тормозим плавно, а в конце — типичная ошибка: доска опущена на нижний кант.
function slipDemo(sim, t, ls, side) { // side: −1 пятки, +1 носки
  const th0 = side < 0 ? HEEL_FACING(sim.toeSign) : TOE_FACING(sim.toeSign);
  const dt = Math.max(0, Math.min(0.05, t - (ls.lastT ?? t))); ls.lastT = t;
  if (ls.m == null) ls.m = 0.4;
  const heel = side < 0;
  const lift = heel ? 'носки' : 'пятки', press = heel ? 'пятки' : 'носки';
  let vt, caption, dont, look, rate = 0.35, mistake = false;
  const body = heel ? 'таз над пятками, колени согнуты, спина прямая — как будто садишься на высокий стул' : 'колени и голени вперёд, таз над носками, руки впереди';
  if (t < 4) { vt = 0.8; caption = `Стою на ${heel ? 'пяточном' : 'носочном'} канте: ${lift} приподняты, ${body}. Скольжу медленно.`; look = `Доска стоит на ${heel ? 'пяточном' : 'носочном'} канте. Смотри на подсвеченную панель канта: ${lift} приподняты, доска не плоская.`; dont = heel ? 'не сгибайся в пояснице и не тянись попой назад — вес уйдёт за пятки' : 'не наклоняйся вперёд одной спиной — колени должны идти вперёд вместе с телом'; }
  else if (t < 9) { vt = 2.6; caption = `Чуть опускаю ${lift} — кант меньше, доска скользит быстрее. Смотри на скорость — она растёт.`; look = 'Кант стал меньше. Смотри: угол на панели канта упал, а скорость (км/ч) растёт.'; dont = `не опускай ${lift} до конца — доска не должна стать плоской`; }
  else if (t < 13) { vt = 2.6 * (13 - t) / 4; caption = `Плавно поднимаю ${lift} — кант растёт, скорость падает. Торможу постепенно.`; look = 'Кант снова растёт. Смотри: угол на панели канта больше, скорость падает.'; dont = `не дёргай ${lift} вверх рывком — резкий кант на скорости опрокидывает`; }
  else if (t < 15) { vt = 0; caption = `Полная остановка: кант держит, вес на ${press}, доска стоит поперёк склона.`; look = 'Остановка. Смотри: доска поперёк склона, кант держит, скорость 0, колени согнуты.'; dont = 'не выпрямляй ноги на остановке — прямые ноги не держат кант'; }
  else if (t < 18) { vt = 1.5; caption = `Снова чуть опускаю ${lift} — поехали. Взгляд вперёд, не под ноги.`; look = 'Кант чуть меньше, и доска поехала. Смотри на голову: взгляд вперёд по склону.'; dont = 'не смотри на доску — смотри на склон перед собой'; }
  else { mistake = true; caption = `ОШИБКА: опустил ${lift} слишком сильно — доска легла на нижний кант, и он цепляет снег…`; look = `Ошибка: ${lift} опущены, кант на панели ушёл в ноль и дальше. Смотри, как нижний край доски врезается в снег и тело летит вниз по склону.`; dont = `${lift} всегда чуть приподняты, пока едешь боком`; }
  let target;
  if (mistake) { target = -0.2; rate = 0.18; } // медленно, чтобы было видно, как доска ложится на нижний кант
  else {
    // регулятор скорости: быстрее нужного — больше канта; кант меняется плавно
    ls.mi = clamp((ls.mi ?? 0.3) + (sim.speed - vt) * 0.25 * dt, 0.12, 0.6);
    target = vt === 0 ? 0.55 : clamp(ls.mi + 0.3 * (sim.speed - vt), 0.12, 0.6);
  }
  ls.m += clamp(target - ls.m, -rate * dt, rate * dt);
  return { edge: side * ls.m, weight: weightForHeading(sim, th0), rot: 0, caption, dont, look, focus: 'edge', slow: mistake ? 0.4 : null, mistake };
}

