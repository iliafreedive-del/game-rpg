export function recommendBoard({ height, weight, level, boot }) {
  // средняя из двух привычных таблиц: по росту (≈ 0.86 роста) и по весу; новичку короче, для карвинга длиннее
  const L = Math.round((height * 0.86 + 116 + weight * 0.5) / 2 + (level === 'new' ? -3 : level === 'carve' ? 3 : 0));
  const lo = L - 2, hi = L + 2, out = [];
  out.push(['ok', `Длина: <b>${lo}–${hi} см</b> — примерно до подбородка или носа. ${level === 'new' ? 'Короткая доска легче поворачивается и прощает ошибки.' : level === 'carve' ? 'Длиннее — устойчивее на скорости и держит дугу.' : 'Золотая середина: и повернуть легко, и на скорости не болтает.'}`]);
  if (weight > 90 && level === 'new') out.push(['warn', 'При весе больше 90 кг не бери самую мягкую доску: она будет проваливаться под тобой. Средняя жёсткость.']);
  out.push(['ok', level === 'new' ? 'Жёсткость: <b>мягкая</b> (2–4 из 10). Доска сама гнётся под тобой и не наказывает за ошибку.'
    : level === 'mid' ? 'Жёсткость: <b>средняя</b> (4–6 из 10) — универсальная.' : 'Жёсткость: <b>средняя или жёсткая</b> (6–8 из 10): держит кант на скорости.']);
  out.push(['ok', level === 'new' ? 'Прогиб: <b>рокер или гибрид</b> (под ногами ровно, нос и хвост приподняты) — меньше ловит кант.'
    : level === 'mid' ? 'Прогиб: <b>гибрид</b> — прощает ошибки и держит кант.' : 'Прогиб: <b>кэмбер</b> (доска выгнута дугой вверх) — лучше держит резаную дугу.']);
  if (boot >= 44.5) out.push(['warn', `Ботинок ${boot}: бери <b>широкую доску</b> (в названии буква W). На обычной носок и пятка торчат за край и цепляют снег в повороте.`]);
  else if (boot >= 43) out.push(['ok', `Ботинок ${boot}: обычная ширина подойдёт, но проверь — носок и пятка не должны торчать за край больше чем на 1–2 см.`]);
  else out.push(['ok', `Ботинок ${boot}: обычная ширина. Слишком широкая доска для маленькой ноги поворачивает тяжелее.`]);
  return { length: L, lo, hi, items: out };
}
