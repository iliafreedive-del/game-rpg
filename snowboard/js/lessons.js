export function evaluateBindings({ front, rear, width, height }) {
  const out = [];
  const rec = Math.round(height * 0.31);
  if (front < 6) out.push(['bad', `Передняя ${fmt(front)}: мало. Колено передней ноги не направлено к носу — доску трудно вести в поворот. Ставь +12…+21°.`]);
  else if (front > 27) out.push(['warn', `Передняя ${fmt(front)}: много для софтбутс. Это ближе к жёсткому «альпийскому» стилю. Для начала +12…+21°.`]);
  else out.push(['ok', `Передняя ${fmt(front)}: хорошо — носок и колено смотрят чуть к носу доски.`]);
  if (rear > front) out.push(['bad', `Задняя ${fmt(rear)} больше передней ${fmt(front)}: колени смотрят навстречу, бёдра скручиваются. Задняя должна быть меньше передней.`]);
  else if (rear < -18) out.push(['warn', `Задняя ${fmt(rear)}: очень сильная «утка». Колено задней ноги выворачивается наружу.`]);
  else if (rear >= -15 && rear <= 12) out.push(['ok', `Задняя ${fmt(rear)}: в разумном диапазоне (−15…+12°).`]);
  else out.push(['warn', `Задняя ${fmt(rear)}: на грани разумного диапазона.`]);
  if (front - rear > 36) out.push(['warn', `Разница ${front - rear}° велика — колени разъезжаются в стороны.`]);
  if (Math.abs(front) < 1 && Math.abs(rear) < 1) out.push(['bad', 'Обе по нулям: ступни поперёк. Вести доску коленями почти невозможно.']);
  if (width < rec - 5) out.push(['warn', `Ширина ${width} см узковата. Для роста ${height} см ориентир ≈ ${rec} см (чуть шире плеч).`]);
  else if (width > rec + 6) out.push(['warn', `Ширина ${width} см широковата: трудно сгибать колени и быстро менять кант. Ориентир ≈ ${rec} см.`]);
  else out.push(['ok', `Ширина ${width} см подходит для роста ${height} см (ориентир ≈ ${rec} см, примерно ширина плеч).`]);
  return out;
}
const fmt = (a) => (a > 0 ? '+' : '') + a + '°';

