// Работа центром тяжести по фазам поворота + подпись, что сейчас делает инструктор.
function turnPhases(c, sim, t) {
  if (t < 2.5) return { ...c, weight: 0.5, caption: 'Старт: таз вперёд, вес на переднюю ногу — так доска разгоняется и слушается. Новички часто «сидят» на задней.' };
  if (c.braking) return { ...c, weight: 0, caption: 'Завершение: довожу доску поперёк склона, вес в центр — кант гасит скорость.' };
  if (Math.abs(c.err) > 0.3) return { ...c, weight: 0.55, caption: 'Начало поворота: таз вперёд, ~65% веса на переднюю ногу, взгляд и плечи — в новый поворот.' };
  return { ...c, weight: 0.25, caption: 'Ведение: держу кант, таз над доской, вес чуть впереди (~57%). Колени мягкие.' };
}

// Линия через центры ворот (косинусная интерполяция) — по ней едет инструктор.
function gatePathU(gates, s) {
  const pts = [{ u: 0, s: 0 }, ...gates];
  for (let i = 0; i < pts.length - 1; i++) {
    const a = pts[i], b = pts[i + 1];
    if (s <= b.s) { const k = clamp((s - a.s) / (b.s - a.s), 0, 1); return a.u + (b.u - a.u) * (1 - Math.cos(Math.PI * k)) / 2; }
  }
  return pts[pts.length - 1].u;
}

function followGates(lesson, sim, { look = 6, k = 1.4, max = 0.6, rotK = 0.5, vTarget = 7, weight = 0.25 } = {}) {
  const ts = sim.s + look;
  const thd = Math.atan2(gatePathU(lesson.gates || lesson.path, ts) - sim.u, look);
  const vdir = sim.speed > 1 ? Math.atan2(sim.vu, sim.vs) : sim.theta;
  const err = wrapAngle(thd - vdir);
  let side = Math.sign(err) || 1;
  let mag = clamp(Math.abs(err) * k, 0, max);
  const lead = wrapAngle(sim.theta - vdir) * side; // насколько доска уже опережает траекторию
  let rot = side * clamp(Math.abs(err) * 2 - Math.max(0, lead) * 3, 0, 1) * rotK;
  const over = sim.speed - vTarget;
  if (over > 0) { // слишком быстро: доворачиваю доску сильнее траектории — юз гасит скорость
    rot = clamp(rot + side * over * 0.4, -1, 1);
    mag = Math.min(mag, 0.3);
  }
  // идём боком — стоим только на верхнем (заднем по ходу) канте, никогда не плоско
  if (Math.abs(sim.vLat) > 0.8) {
    const safe = -Math.sign(sim.vLat);
    if (side !== safe) { rot = side * 0.8; side = safe; mag = 0.12; } else mag = Math.max(mag, 0.15); // нос — вниз поворотом, а кант меняю, когда юз погас
  }
  return { edge: side * sim.toeSign * mag, weight, rot, err, braking: over > 0 };
}

function gateCheck(lesson, sim, ls, need) {
  const gs = lesson.gates;
  if (ls.gi < gs.length && sim.s >= gs[ls.gi].s) {
    const g = gs[ls.gi];
    const ok = Math.abs(sim.u - g.u) <= g.w / 2;
    ls.res.push(ok);
    if (ok) ls.ok++; else ls.miss++;
    ls.gi++;
  }
  const total = gs.length;
  const finished = ls.gi >= total;
  const r = { done: finished && ls.ok >= need, text: `Ворота ${ls.ok}/${total}`, p: ls.gi / total };
  if (finished && ls.ok < need) r.fail = `Пройдено ${ls.ok} из ${total} ворот, нужно ${need}. Начинай поворот раньше — ещё до ворот.`;
  if (!finished && ls.miss > total - need) r.fail = `Пропущено ${ls.miss} ворот. Поворачивай раньше и заканчивай поворот поперёк склона, чтобы не разгоняться.`;
  return r;
}

