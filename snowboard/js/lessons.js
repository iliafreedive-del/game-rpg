export function evaluatePosture(p) {
  const r = {};
  r.knee = p.knee < 0.28 ? ['bad', 'Ноги почти прямые. Нет амортизации: любой бугор выбивает из равновесия, а кант держится хуже.']
    : p.knee > 0.8 ? ['warn', 'Слишком низко. Ноги быстро забьются, и не останется запаса, чтобы присесть на бугре.']
    : ['ok', 'Колени и голеностопы мягко согнуты — как у вратаря перед ударом.'];
  r.hinge = p.hinge > 0.35 ? ['bad', 'Согнулся в поясе: попа уходит назад, колени выпрямляются. На носочном канте это главная причина «не держит».']
    : ['ok', 'Спина ровная, корпус лишь слегка наклонён вперёд. Сгибаемся в коленях, а не в пояснице.'];
  r.weight = p.weight < -0.12 ? ['bad', 'Вес на задней ноге. Доска «уезжает» вперёд и не слушается поворота. Самая частая ошибка новичков.']
    : p.weight > 0.5 ? ['warn', 'Слишком много на передней. Нос зарывается, хвост начинает гулять.']
    : ['ok', 'Вес по центру или чуть больше на передней ноге (55–60%).'];
  r.rot = Math.abs(p.rot) > 0.3 ? ['bad', 'Плечи развёрнуты. Корпус скручен относительно доски — она начнёт поворачивать сама или, наоборот, «застрянет».']
    : ['ok', 'Плечи вдоль доски, над ней. Передняя рука смотрит на нос.'];
  r.gaze = p.gaze < 0.6 ? ['bad', 'Смотришь под ноги. Голова тяжёлая: куда смотришь — туда и падаешь. Взгляд на 3–5 м вперёд по ходу.']
    : ['ok', 'Голова поднята, взгляд туда, куда едешь.'];
  r.arms = p.arms > 0.65 ? ['bad', 'Руки машут — значит, баланс ловится руками, а не ногами. Каждый взмах закручивает корпус.']
    : p.arms < 0.15 ? ['warn', 'Руки прижаты: тело зажато. Расслабь их и держи чуть впереди.']
    : ['ok', 'Руки расслаблены, чуть впереди и в стороны, «над доской».'];
  return r;
}

