export function chordMidis(ch) {
  return ch.frets.map((f, i) => (f < 0 ? null : OPEN[i] + f));
}
export function chordPcs(ch) {
  return [...new Set(chordMidis(ch).filter(m => m != null).map(m => m % 12))];
}

