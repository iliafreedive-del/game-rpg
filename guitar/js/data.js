const LAT = ['C', 'C♯', 'D', 'D♯', 'E', 'F', 'F♯', 'G', 'G♯', 'A', 'A♯', 'B'];
const RU = ['до', 'до♯', 'ре', 'ре♯', 'ми', 'фа', 'фа♯', 'соль', 'соль♯', 'ля', 'ля♯', 'си'];

export function noteName(midi) {
  const pc = ((Math.round(midi) % 12) + 12) % 12;
  return { lat: LAT[pc], ru: RU[pc], oct: Math.floor(Math.round(midi) / 12) - 1, pc };
}
export const pcName = pc => `${RU[pc]} (${LAT[pc]})`;

// strNum: 1..6 (как считают гитаристы) -> индекс в OPEN
export const sIdx = n => 6 - n;
export const midiAt = (strNum, fret) => OPEN[sIdx(strNum)] + fret;

