export function pickTargets(chord, pick, times = 2) {
  const ch = CHORDS[chord], b = bassString(chord), out = [];
  for (let k = 0; k < times; k++) for (const p of PICKS[pick].seq) {
    const s = p === 'B' ? b : p;
    out.push({ s, f: ch.frets[sIdx(s)], label: p === 'B' ? 'p' : PIMA[p], chord });
  }
  return out;
}

