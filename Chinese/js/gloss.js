const TIME = new Set(['今天', '明天', '昨天', '现在', '每天', '早上', '晚上', '星期一', '星期天', '星期六', '星期', '八点', '三点']);
const PLACES = new Set(['家', '学校', '银行', '医院', '公司', '公园', '北京', '上海', '中国', '商店', '房间', '桌子', '哪儿', '哪里', '这儿', '那儿', '这里', '外面', '厕所']);
const look = w => LW.get(w) || F[w]?.[0];

// tokens — слова фразы как написаны, i — индекс нажатого.
export function gloss(tokens, i) {
  const w = tokens[i], next = tokens[i + 1], prev = tokens[i - 1];
  const res = { word: w, ru: '', note: '', rule: null, phrase: null };
  const py = pyOf(w);
  let ru = '';
  if (w === '在') {
    if (PLACES.has(next) || !next) { ru = 'находиться; в, на'; res.note = '<b>在 + место</b> — где находится или где происходит действие. Место с 在 ставится перед глаголом.'; res.rule = next && tokens.slice(i + 2).length ? 'zai_place' : 'zai'; }
    else { ru = 'сейчас (идёт действие)'; res.note = '<b>在 + глагол</b> — действие идёт прямо сейчас: 我在吃饭 — я ем.'; res.rule = 'zai_prog'; }
  } else if (w === '了' && !next) {
    ru = '(стало так / сделал)'; res.note = '<b>了</b> в конце фразы — «стало так» или «уже сделано».'; res.rule = 'le';
  } else if (w === '很' && next === '多') {
    ru = 'очень'; res.note = '很多 — много.';
  } else if (F[w]) {
    [ru, res.note, res.rule] = F[w];
  } else if (LW.has(w)) {
    ru = LW.get(w);
    if (TIME.has(w)) { res.note = 'Слово времени: стоит перед глаголом (или в самом начале фразы).'; res.rule = 'time_order'; }
  } else if (w.length > 1) {
    // незнакомое составное слово — разберём по частям, которые уже встречались
    const parts = [];
    for (let p = 0; p < w.length;) {
      let L = Math.min(4, w.length - p);
      while (L > 1 && !look(w.slice(p, p + L))) L--;
      parts.push(w.slice(p, p + L)); p += L;
    }
    if (parts.some(look)) { ru = parts.map(x => look(x) || '…').join(' + '); res.note = `Слово из частей: ${parts.map(x => `<b>${x}</b> ${pyOf(x)}${look(x) ? ` — ${look(x)}` : ''}`).join(', ')}.`; }
  }
  if (!ru && /^[一二三四五六七八九十零两]+$/.test(w)) ru = 'число';
  if (prev === '不' && !res.note && ru) res.note = 'Перед ним 不 — «не».';
  res.ru = `${py}${ru ? ' — ' + ru : ''}`;
  return res;
}
